#!/usr/bin/env python3
"""Cut the AnyWhere app icons from the supplied logo.

    python3 -I brand/make-icons.py

Input:   brand/AnyWhere-logo-source.png   (1254 x 1254, the logo on a dark backdrop)
Outputs: brand/AnyWhere-ios-1024.png      full-bleed square; iOS rounds the corners itself
         brand/AnyWhere-mac-1024.png      the tile on Apple's macOS icon grid (824 px body,
                                          transparent corners, soft drop shadow)
         iPhoneRemote/SpoofRemote/Assets.xcassets/AppIcon.appiconset/AppIcon.png  (copy of the iOS one)
         Sources/iosgpsspoofer-gui/BrandLogoData.swift   a 256 px copy of the Mac icon as base64, for the
                                          sidebar and the Dock icon of unpackaged runs. (No SwiftPM resource
                                          bundle: a packaged .app does not carry one.)

Needs Pillow and NumPy. The outputs are committed, so building the app does not.
"""
from pathlib import Path

import numpy as np
from PIL import Image, ImageChops, ImageDraw, ImageFilter

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "brand" / "AnyWhere-logo-source.png"
IOS_OUT = ROOT / "brand" / "AnyWhere-ios-1024.png"
MAC_OUT = ROOT / "brand" / "AnyWhere-mac-1024.png"
LOGO_SWIFT = ROOT / "Sources" / "iosgpsspoofer-gui" / "BrandLogoData.swift"
APPICONSET = ROOT / "iPhoneRemote" / "SpoofRemote" / "Assets.xcassets" / "AppIcon.appiconset" / "AppIcon.png"


def tile_bounds(rgb: np.ndarray) -> tuple[int, int, int, int]:
    """The rounded tile's bounding box (left, top, right, bottom), found from its edge
    along the middle row and column: the tile is brighter than the backdrop."""
    backdrop = rgb[4:30, 4:30].reshape(-1, 3).mean(axis=0)
    height, width, _ = rgb.shape

    def edges(line: np.ndarray) -> tuple[int, int]:
        lift = line.sum(axis=1) - backdrop.sum()
        inside = np.flatnonzero(lift > 38)
        return int(inside[0]), int(inside[-1])

    left, right = edges(rgb[height // 2])
    top, bottom = edges(rgb[:, width // 2])
    return left, top, right + 1, bottom + 1


def corner_radius(rgb: np.ndarray, box: tuple[int, int, int, int]) -> float:
    """The tile's corner radius, from where its top-left corner meets the diagonal.
    On a circular corner of radius r the diagonal enters the tile 0.2929 r in from each edge."""
    backdrop = rgb[4:30, 4:30].reshape(-1, 3).mean(axis=0)
    left, top, _, _ = box
    for d in range(0, 400):
        px = rgb[top + d, left + d]
        if px.sum() - backdrop.sum() > 38:
            return d / 0.2929
    raise SystemExit("could not find the tile's corner")


def rounded_mask(size: int, radius: float, inset: float = 1.5) -> Image.Image:
    """An anti-aliased rounded-rectangle mask, drawn 4x and scaled down."""
    scale = 4
    big = Image.new("L", (size * scale, size * scale), 0)
    draw = ImageDraw.Draw(big)
    pad = inset * scale
    draw.rounded_rectangle((pad, pad, size * scale - pad - 1, size * scale - pad - 1), radius=radius * scale, fill=255)
    return big.resize((size, size), Image.LANCZOS)


def write_swift_logo(mac_icon: Image.Image) -> None:
    import base64
    import io

    small = mac_icon.resize((256, 256), Image.LANCZOS)
    buffer = io.BytesIO()
    small.save(buffer, format="PNG", optimize=True)
    encoded = base64.b64encode(buffer.getvalue()).decode("ascii")
    lines = [encoded[i:i + 120] for i in range(0, len(encoded), 120)]
    body = "\n".join(lines)
    LOGO_SWIFT.write_text(
        "// Generated by brand/make-icons.py from the AnyWhere logo. Do not edit by hand.\n"
        "import Foundation\n\n"
        "enum BrandLogoData {\n"
        "    /// The AnyWhere app icon, 256 x 256 px PNG, base64 (line breaks are ignored when decoding).\n"
        '    static let png256Base64 = """\n' + body + '\n"""\n\n'
        "    static var png256: Data? { Data(base64Encoded: png256Base64, options: .ignoreUnknownCharacters) }\n"
        "}\n"
    )


def main() -> None:
    logo = Image.open(SRC).convert("RGB")
    rgb = np.asarray(logo).astype(int)
    left, top, right, bottom = tile_bounds(rgb)
    radius = corner_radius(rgb, (left, top, right, bottom))
    width, height = right - left, bottom - top
    print(f"tile {left},{top}-{right},{bottom} ({width}x{height}), corner radius {radius:.0f}px")

    # The tile is a hair off square; use the shorter side so nothing is stretched.
    side = min(width, height)
    cx, cy = (left + right) / 2, (top + bottom) / 2

    size = int(side)
    x0, y0 = int(round(cx - size / 2)), int(round(cy - size / 2))
    tile_box = (x0, y0, x0 + size, y0 + size)   # exactly square

    # iOS: full bleed, the whole tile. The tile's own corners are rounder than iOS's mask,
    # so the slivers outside the tile's curve are filled with the tile's edge colour
    # instead of the (much darker) backdrop.
    tile_full = logo.crop(tile_box)
    full = size
    mid = full // 2
    ring = np.asarray(tile_full).astype(int)
    edge = np.concatenate([ring[mid, 14:20], ring[mid, full - 20:full - 14], ring[14:20, mid], ring[full - 20:full - 14, mid]])
    edge_colour = tuple(int(v) for v in edge.reshape(-1, 3).mean(axis=0))
    ios_base = Image.new("RGB", tile_full.size, edge_colour)
    ios_base.paste(tile_full, (0, 0), rounded_mask(full, radius, inset=3))
    ios = ios_base.resize((1024, 1024), Image.LANCZOS)
    ios.save(IOS_OUT, optimize=True)
    APPICONSET.parent.mkdir(parents=True, exist_ok=True)
    ios.save(APPICONSET, optimize=True)

    # macOS: the tile itself, masked to its rounded shape, in an 824 px body centred on a
    # 1024 px canvas, with a soft shadow below.
    body = 824
    tile = tile_full.resize((body, body), Image.LANCZOS)
    mask = rounded_mask(body, radius * body / size)
    canvas = Image.new("RGBA", (1024, 1024), (0, 0, 0, 0))

    shadow = Image.new("L", (1024, 1024), 0)
    shadow.paste(mask.point(lambda v: int(v * 0.42)), (100, 100 + 12))
    shadow = shadow.filter(ImageFilter.GaussianBlur(14))
    shadow_rgba = Image.new("RGBA", (1024, 1024), (0, 0, 0, 255))
    shadow_rgba.putalpha(shadow)
    canvas = Image.alpha_composite(canvas, shadow_rgba)

    tile_rgba = tile.convert("RGBA")
    tile_rgba.putalpha(mask)
    canvas.alpha_composite(tile_rgba, (100, 100))
    canvas.save(MAC_OUT, optimize=True)
    write_swift_logo(canvas)
    print("wrote", IOS_OUT.relative_to(ROOT), MAC_OUT.relative_to(ROOT), APPICONSET.relative_to(ROOT))


if __name__ == "__main__":
    main()
